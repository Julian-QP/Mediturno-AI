import {Router} from 'express';
import {requireAuth} from '../middlewares/authMiddleware.js';
import {authorizeDb} from '../middlewares/authorizeDb.js';
import {doctorClinicalDetails,startEncounter,saveEncounter,finishEncounter,createTreatment,linkTreatment,createExam,doctorClinicalList,patientClinicalList,patientCareDetails,updateExam,deleteExam,deleteTreatment,bookFollowup} from '../controllers/clinicalController.js';
const router=Router();router.use(requireAuth);
router.get('/patient',authorizeDb('patient'),patientClinicalList);
router.get('/patient/care-records',authorizeDb('patient'),patientCareDetails);
router.use('/doctor',authorizeDb('doctor'));
router.get('/doctor',doctorClinicalList);
router.get('/doctor/appointments/:id',doctorClinicalDetails);
router.post('/doctor/appointments/:id/start',startEncounter);
router.patch('/doctor/appointments/:id/notes',saveEncounter);
router.post('/doctor/appointments/:id/finish',finishEncounter);
router.post('/doctor/appointments/:id/treatments',createTreatment);
router.post('/doctor/appointments/:id/treatments/:planId/link',linkTreatment);
router.post('/doctor/appointments/:id/exams',createExam);
router.patch('/doctor/appointments/:id/exams/:examId',updateExam);
router.delete('/doctor/appointments/:id/exams/:examId',deleteExam);
router.delete('/doctor/appointments/:id/treatments/:planId',deleteTreatment);
router.post('/doctor/appointments/:id/followup-appointments',bookFollowup);
export default router;
